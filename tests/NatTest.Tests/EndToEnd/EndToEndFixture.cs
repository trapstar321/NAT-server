using System;
using System.Collections.Generic;
using System.IO;
using System.Threading.Tasks;
using NatTest.Common;
using Org.BouncyCastle.Crypto.Parameters;
using Xunit;
using Xunit.Sdk;

namespace NatTest.Tests.EndToEnd
{
    [CollectionDefinition(Name)]
    public sealed class EndToEndCollection : ICollectionFixture<EndToEndFixture>
    {
        internal const string Name = "end-to-end";
    }

    // Builds and starts the real MatchmakingService with throwaway keys and database, generates an introducer key, starts the
    // introducer, and signs in a host and two client accounts. Everything lives in a temp directory removed afterwards.
    public sealed class EndToEndFixture : IDisposable
    {
        private const string Password = "nat end-to-end passphrase";

        private readonly string tempDirectory = Path.Combine(Path.GetTempPath(), "nattest-e2e-" + Guid.NewGuid().ToString("N"));
        private PeerProcess matchmaking;
        private PeerProcess introducer;

        public EndToEndFixture()
        {
            try
            {
                Initialize().GetAwaiter().GetResult();
            }
            catch
            {
                Dispose();
                throw;
            }
        }

        internal MatchmakingApi Api { get; private set; }
        internal int IntroducerPort { get; private set; }
        internal PeerProcess Introducer { get { return introducer; } }
        internal Account Host { get; private set; }
        internal Account Client { get; private set; }
        internal Account OtherClient { get; private set; }

        internal string MatchmakingPublicKeyPath { get { return Path.Combine(tempDirectory, "mm-keys", "mm-nat-signing.pub.pem"); } }
        internal string MatchmakingPrivateKeyPath { get { return Path.Combine(tempDirectory, "mm-keys", "mm-nat-signing.pem"); } }
        internal string IntroducerPublicKeyPath { get { return Path.Combine(tempDirectory, "introducer-keys", "introducer-signing.pub.pem"); } }
        internal string IntroducerPrivateKeyPath { get { return Path.Combine(tempDirectory, "introducer-keys", "introducer-signing.pem"); } }

        // Test-only access to the private keys, to mint tokens MM and the introducer would never issue (expired, wrong player).
        internal ECPrivateKeyParameters MatchmakingPrivateKey { get; private set; }
        internal ECPrivateKeyParameters IntroducerPrivateKey { get; private set; }

        private async Task Initialize()
        {
            if (!File.Exists(TestEnvironment.MatchmakingProject))
                throw new XunitException("MatchmakingService project not found at " + TestEnvironment.MatchmakingProject + "; set NATTEST_MATCHMAKING_PROJECT.");
            Directory.CreateDirectory(tempDirectory);

            string projectDirectory = Path.GetDirectoryName(TestEnvironment.MatchmakingProject);
            PeerProcess.Run("MatchmakingService build", "dotnet", new object[] { "build", TestEnvironment.MatchmakingProject, "-c", "Debug", "-nologo", "-v", "q" }, TimeSpan.FromMinutes(5), projectDirectory);
            string outputDirectory = Path.Combine(projectDirectory, "bin", "Debug", "net9.0");
            string dll = Path.Combine(outputDirectory, "MatchmakingService.dll");

            // Keys are generated by each component's own command, exactly as an operator would.
            PeerProcess.Run("MatchmakingService generate-signing-keys", "dotnet", new object[] { dll, "generate-signing-keys", Path.Combine(tempDirectory, "mm-keys") }, TimeSpan.FromMinutes(1), outputDirectory);
            PeerProcess.Run("introducer generate-key", TestEnvironment.IntroducerExe, new object[] { "generate-key", Path.Combine(tempDirectory, "introducer-keys") }, TimeSpan.FromMinutes(1));
            MatchmakingPrivateKey = SigningKeys.LoadPrivateKeyFile(MatchmakingPrivateKeyPath, "MM NAT key");
            IntroducerPrivateKey = SigningKeys.LoadPrivateKeyFile(IntroducerPrivateKeyPath, "introducer key");

            int httpPort = TestEnvironment.FreeTcpPort();
            matchmaking = PeerProcess.Start("MatchmakingService", "dotnet", new object[] { dll, "--urls", "http://127.0.0.1:" + httpPort }, PeerRuntime.NetFramework, outputDirectory,
                new Dictionary<string, string>
                {
                    { "ASPNETCORE_ENVIRONMENT", "Production" },
                    { "Matchmaking__DatabasePath", Path.Combine(tempDirectory, "matchmaking.db") },
                    { "Matchmaking__Tokens__AuthSigningKeyPath", Path.Combine(tempDirectory, "mm-keys", "mm-auth-signing.pem") },
                    { "Matchmaking__Tokens__NatSigningKeyPath", MatchmakingPrivateKeyPath },
                    // The test hosts do not send MM heartbeats, and every test shares one client IP.
                    { "Matchmaking__SessionExpirationTimeout", "00:10:00" },
                    { "Matchmaking__MaxSessionsPerIp", "1000" },
                    { "Matchmaking__RateLimits__GlobalPermitLimit", "100000" },
                    { "Matchmaking__RateLimits__CreatePermitLimit", "100000" },
                    { "Matchmaking__RateLimits__RegisterPermitLimit", "100000" },
                    { "Matchmaking__RateLimits__LoginPermitLimit", "100000" }
                });
            Api = new MatchmakingApi(new Uri("http://127.0.0.1:" + httpPort));
            var deadline = DateTime.UtcNow.AddSeconds(60);
            while (!await Api.IsHealthy())
            {
                if (matchmaking.HasExited || DateTime.UtcNow > deadline) throw new XunitException("MatchmakingService did not start.\n" + matchmaking.Output);
                await Task.Delay(200);
            }

            IntroducerPort = TestEnvironment.FreeUdpPort();
            introducer = PeerProcess.Start("introducer", TestEnvironment.IntroducerExe, new object[]
            {
                "--bind", "127.0.0.1", "--port", IntroducerPort, "--timeout", "600",
                "--mm-public-key", MatchmakingPublicKeyPath, "--key", IntroducerPrivateKeyPath
            });
            await introducer.WaitForLine("Listening on");

            Host = await Api.RegisterOrLogin("host@nattest.example", Password);
            Client = await Api.RegisterOrLogin("client@nattest.example", Password);
            OtherClient = await Api.RegisterOrLogin("other-client@nattest.example", Password);
        }

        public void Dispose()
        {
            if (introducer != null) introducer.Dispose();
            if (matchmaking != null) matchmaking.Dispose();
            if (Api != null) Api.Dispose();
            try
            {
                if (Directory.Exists(tempDirectory)) Directory.Delete(tempDirectory, true);
            }
            catch (IOException) { }
            catch (UnauthorizedAccessException) { }
        }
    }
}
